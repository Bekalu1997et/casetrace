import { test, expect } from "@playwright/test";
import { writeFile } from "node:fs/promises";

test("CASE-001 investigation resolves actual evidence and survives refresh", async ({ page, request }, testInfo) => {
  test.setTimeout(120000);
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await page.getByLabel("Search patients").fill("Daniel");
  await page.getByRole("link", { name: "Daniel M. (synthetic)" }).click();
  await expect(page.getByRole("heading", { name: "Daniel M. (synthetic)" })).toBeVisible();
  await page.getByRole("link", { name: "Laboratory", exact: true }).click();
  await expect(page.getByRole("link", { name: /^LAB-/ }).first()).toBeVisible();
  await page.getByRole("button", { name: "Start investigation", exact: true }).click();
  await page.getByRole("button", { name: "Begin investigation", exact: true }).click();
  await expect(page).toHaveURL(/\/investigations\/INV-/);
  const id = new URL(page.url()).pathname.split("/").at(-1)!;
  await expect(page.getByRole("link", { name: "Open investigation report →" })).toBeVisible({ timeout: 90000 });
  const state = await (await request.get(`${process.env.API_TEST_URL ?? "http://localhost:8000"}/api/investigations/${id}`)).json();
  const findings = await (await request.get(`${process.env.API_TEST_URL ?? "http://localhost:8000"}/api/investigations/${id}/findings`)).json();
  expect(["completed", "completed_with_limitations"]).toContain(state.status);
  expect(findings.items.some((finding: { status: string }) => finding.status === "verified")).toBe(true);
  await page.locator("#investigation-findings > summary").click();
  await page.getByRole("button", { name: "Compare source records" }).first().click();
  await expect(page.getByRole("heading", { name: "Compare original records" })).toBeVisible();
  await expect(page.getByText("Cited field:").first()).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("workspace-comparison.png") });
  await page.getByRole("button", { name: "Close evidence" }).click();
  await page.getByText("Timeline and hypotheses", { exact: true }).click();
  await expect(page.getByLabel("Event category")).toBeVisible();
  await page.getByRole("button", { name: /^Open source / }).first().click();
  await expect(page.getByRole("heading", { name: "Original evidence" })).toBeVisible();
  await page.getByRole("button", { name: "Close evidence" }).click();
  await page.locator("details.compact-activity > summary").click();
  await expect(page.getByText("Persisted execution history")).toBeVisible();
  const earlier = page.getByRole("button", { name: /^Show earlier activity/ });
  while (await earlier.count()) await earlier.click();
  await expect(page.getByText(/tool · completed/).first()).toBeVisible();
  await page.getByRole("button", { name: /^Open source / }).first().click();
  await page.reload();
  await expect(page.getByRole("link", { name: "Open investigation report →" })).toBeVisible();
  await expect(page.getByRole("region", { name: /^Original source / })).toBeVisible();
  await page.getByRole("link", { name: "Open investigation report →" }).click();
  await expect(page.getByRole("heading", { name: "Executive summary" })).toBeVisible();
  const report = await (await request.get(`${process.env.API_TEST_URL ?? "http://localhost:8000"}/api/investigations/${id}/report`)).json();
  await testInfo.attach("persisted-state.json", { body: JSON.stringify(state, null, 2), contentType: "application/json" });
  await testInfo.attach("persisted-report.json", { body: JSON.stringify(report, null, 2), contentType: "application/json" });
  await writeFile(testInfo.outputPath("persisted-report.json"), JSON.stringify(report, null, 2));
  await writeFile(testInfo.outputPath("persisted-state.json"), JSON.stringify(state, null, 2));
  if (process.env.REASONING_TEST === "structured") {
    expect(report.verified_findings.some((finding: { anchors: { char_start?: number | null }[] }) =>
      finding.anchors.some(anchor => anchor.char_start != null))).toBe(true);
  }
  await expect(page.getByRole("heading", { name: report.summary.headline })).toBeVisible();
  await page.getByRole("button", { name: / · supports$/ }).first().click();
  await expect(page.getByRole("region", { name: "Report source evidence" })).toBeVisible();
  await expect(page.getByText("Cited field:").first()).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("report-desktop.png") });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("report-mobile.png") });
  await page.emulateMedia({ media: "print" });
  await page.pdf({ path: testInfo.outputPath("report-print.pdf"), format: "A4" });
  expect(errors).toEqual([]);
});
